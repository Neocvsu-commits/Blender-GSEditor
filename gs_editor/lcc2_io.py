def _integer(value, label, minimum=0):
    try:
        result = operator.index(value)
    except TypeError as ex:
        raise ValueError(f'LCC2 {label}必须为整数') from ex
    if isinstance(value, bool) or result < minimum:
        raise ValueError(f'LCC2 {label}必须不小于 {minimum}')
    return result


def _bounds(value):
    if len(value) != 2 or any(len(v) != 3 for v in value):
        raise ValueError('LCC2 包围框必须包含三维最小值和最大值')
    lo, hi = ([float(v) for v in row] for row in value)
    if not all(math.isfinite(v) for row in (lo, hi) for v in row):
        raise ValueError('LCC2 包围框包含无效坐标')
    if any(a > b for a, b in zip(lo, hi)):
        raise ValueError('LCC2 包围框最小值超过最大值')
    return {'min': lo, 'max': hi}


def _dataset(dataset):
    """Validate the small descriptors before starting expensive compression."""
    depth = _integer(dataset['levels'], 'LOD 层数', 1)
    count = _integer(dataset['count'], '原始点数', 1)
    expected = [_integer(n, 'LOD 点数', 1) for n in dataset['lod_counts']]
    if len(expected) != depth or expected[0] != count:
        raise ValueError('LCC2 LOD 点数与原始点数不一致')
    bounds = _bounds(dataset['bounds'])
    cells, coordinates = [], set()
    totals = [0] * depth
    for cell in dataset['cells']:
        coordinate = (_integer(cell['x'], '分块 X 索引'),
                      _integer(cell['y'], '分块 Y 索引'))
        if coordinate in coordinates:
            raise ValueError('LCC2 空间分块索引重复')
        coordinates.add(coordinate)
        box = _bounds(cell['bounds'])
        if any(box['min'][axis] < bounds['min'][axis]
               or box['max'][axis] > bounds['max'][axis] for axis in range(3)):
            raise ValueError('LCC2 场景包围框未包含所有空间分块')
        if len(cell['levels']) != depth:
            raise ValueError('LCC2 所有分块必须具有相同的 LOD 层数')
        levels = []
        for level, entry in enumerate(cell['levels']):
            n = _integer(entry['count'], '分块点数', 1)
            if levels and n > levels[-1]['count']:
                raise ValueError('LCC2 粗层点数不能超过上一精细层')
            path = Path(entry['path'])
            if not path.is_file():
                raise ValueError(f'LCC2 分块 PLY 不存在：{path.name}')
            levels.append({'path': path, 'count': n})
            totals[level] += n
        cells.append({'bounds': box, 'levels': levels})
    if not cells or totals != expected:
        raise ValueError('LCC2 空间分块的合计点数与 LOD 点数不一致')
    return depth, count, totals, bounds, cells


def write_lcc2(dataset, folder):
    """Write ``meta.lcc2``, ``blocks/*.sog`` and the notice into an empty folder.

    Return ``(original_count, notes)``.  The caller publishes the complete folder
    or ZIP only after success, and cleans this temporary directory on failure or
    cancellation.  All child encoders stay in the worker's process group.
    """
    depth, count, totals, bounds, cells = _dataset(dataset)
    destination = Path(folder)
    destination.mkdir(parents=True, exist_ok=True)
    if any(destination.iterdir()):
        raise ValueError('LCC2 输出工作目录必须为空')
    blocks = destination / 'blocks'
    blocks.mkdir()
    files = []
    root = {'id': '0', 'boundingBox': bounds, 'data': None,
            'splatFiles': files, 'childNum': len(cells), 'child': {}}
    notes = []
    sh_degree = None

    for cell_index, cell in enumerate(cells):
        parent = root
        node_id = f'0-{cell_index}'
        for level in range(depth - 1, -1, -1):
            entry = cell['levels'][level]
            name = f'blocks/cell_{cell_index:06d}_lod_{level:02d}.sog'
            chunk_count, chunk_notes = write_sog_from_ply(entry['path'], destination / name)
            if chunk_count != entry['count']:
                raise ValueError('LCC2 分块 PLY 的实际点数与 LOD 索引不一致')
            # A scene's chunks must have uniform SH bands. Reading the tiny SOG
            # manifest avoids rescanning every input PLY just to inspect its SH.
            with zipfile.ZipFile(destination / name) as bundle:
                chunk_meta = json.loads(bundle.read('meta.json'))
            degree = chunk_meta.get('shN', {}).get('bands', 0)
            if sh_degree is None:
                sh_degree = degree
            elif degree != sh_degree:
                raise ValueError('LCC2 各分块的球谐阶数不一致')
            for note in chunk_notes:
                if note not in notes:
                    notes.append(note)

            node = {'id': node_id, 'boundingBox': cell['bounds'],
                    'data': {'3dgs': {'name': len(files), 'start': 0,
                                      'count': chunk_count}},
                    'childNum': 1 if level else 0}
            files.append(name)
            if parent is root:
                root['child'][str(cell_index)] = node
            else:
                parent['child'] = {'0': node}
            parent = node
            node_id += '-0'

    meta = {
        'version': '0.0.3',
        'name': str(dataset.get('name', 'Gaussian Scene')),
        'description': 'Spatial Gaussian LODs generated by GS Editor',
        'epsg': 0,
        'guid': str(uuid.uuid4()),
        'source': 'ply',
        'dataType': 'None',
        'offset': [0.0, 0.0, 0.0],
        'shift': [0.0, 0.0, 0.0],
        'scale': [1.0, 1.0, 1.0],
        'fileType': 'quality' if sh_degree else 'portable',
        'totalSplats': sum(totals),
        'lodSplats': totals,
        'totalLevels': depth,
        'boundingBox': bounds,
        'splatType': '.sog',
        'virtualLoD': None,
        'env': None,
        'splatExtraAttributes': None,
        'root': root,
        'renderingHints': {'renderMethod': 'splatting',
                           'renderMethodVariant': 'ewa',
                           'sortingMethod': 'depth',
                           'cameraModel': 'pinhole'},
    }
    (destination / 'FORMAT_NOTICE.txt').write_text(_NOTICE, encoding='utf-8')
    # Publish the manifest last: it must not describe incomplete chunk files.
    (destination / 'meta.lcc2').write_text(
        json.dumps(meta, ensure_ascii=False, separators=(',', ':'), allow_nan=False),
        encoding='utf-8')
    notes.insert(0, f'LCC2 包含 {len(cells):,} 个空间分块和 {depth} 级 LOD；需要支持 LCC2 的网页运行时')
    notes.append('LOD0 保留全部原始高斯；粗层为合并近似，SOG 存储使用有损量化')
    return count, notes
