"""Write LCC2 0.0.3 spatial LOD trees with independently streamed SOG chunks.

The caller owns the temporary output directory and the oriented LOD dataset. Input
levels are finest first; LCC2 tree depth runs in the opposite direction.  The
root has no splats, and each spatial cell is a same-depth, single-child chain.
This is supported by the public LCC2 schema and PlayCanvas's LCC2 parser.

Dataset contract (the same contract is used by the LCC1 writer)::

    {
        'bounds': [[min_x, min_y, min_z], [max_x, max_y, max_z]],
        'cells': [{'x': int, 'y': int, 'bounds': [[min], [max]],
                   'levels': [{'path': canonical_ply_path, 'count': int}, ...]}],
        'cell_length': [size_x, size_y],
        'levels': int, 'count': int, 'lod_counts': [int, ...]
    }

All cells must have the same number of levels.  Bounds should enclose the
Gaussian extents at every level, not only the centers.  No axis transform or
simplification is performed here. The export operator chooses the basis
(standard LCC is Z-up); the shared dataset builder creates the LODs.

Specification: https://github.com/xgrids/LCC2Whitepaper
Runtime: https://github.com/playcanvas/engine/blob/main/src/framework/parsers/gsplat-lcc2.js
"""

